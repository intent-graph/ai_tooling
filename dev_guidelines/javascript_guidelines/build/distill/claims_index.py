"""Build a compact index of every stage-3 claim, and split full claim rows by branch.

  python3 claims_index.py index    -> build/distill/claims_index.md (id, slot, level, agreement,
                                      claim, tags), the routing agent's input
  python3 claims_index.py split    -> reads build/distill/routing.md
                                      (| claim_id | branch | group | note |), checks every claim is
                                      routed exactly once, and writes
                                      build/distill/branches/<BRANCH>/claims.md with the full rows

Claim slots: build/research/<NN>_*/result.md for 01 to 10 and 13.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

BUILD = Path(__file__).resolve().parent.parent
HEADER = ["id", "claim", "level", "stack", "since", "sources", "agreement", "certainty", "mechanism", "quote", "tags"]
BRANCHES = ["SUBSET", "CONTRACTS", "CONTROL", "STRUCTURE", "DEFENSE", "DEPENDENCIES", "VERIFICATION", "RUNTIME"]
CLAIM_ID = re.compile(r"[A-Z][A-Z0-9]*-C\d+")


def claims():
    for path in sorted((BUILD / "research").glob("*/result.md")):
        slot = path.parent.name
        if not re.match(r"(0[1-9]|10|13)_", slot):
            continue
        for line in path.read_text().splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if line.startswith("|") and len(cells) == len(HEADER) and CLAIM_ID.fullmatch(cells[0]):
                yield slot, line, dict(zip(HEADER, cells))


def index():
    out = ["# Claims index (generated by claims_index.py; do not edit)", "",
           "| id | slot | level | agreement | claim | tags |", "|---|---|---|---|---|---|"]
    n = 0
    for slot, _, c in claims():
        out.append(f"| {c['id']} | {slot} | {c['level']} | {c['agreement']} | {c['claim']} | {c['tags']} |")
        n += 1
    (BUILD / "distill" / "claims_index.md").write_text("\n".join(out) + "\n")
    print(f"indexed {n} claims")


def split():
    rows = {c["id"]: (slot, line) for slot, line, c in claims()}
    routed, errors = defaultdict(list), []
    seen = set()
    for line in (BUILD / "distill" / "routing.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not (line.startswith("|") and cells and CLAIM_ID.fullmatch(cells[0])):
            continue
        cid, branch = cells[0], cells[1]
        group = cells[2] if len(cells) > 2 else "-"
        if cid in seen:
            errors.append(f"{cid} routed twice")
        seen.add(cid)
        if cid not in rows:
            errors.append(f"{cid} routed but not a claim")
        elif branch not in BRANCHES:
            errors.append(f"{cid} routed to unknown branch {branch}")
        else:
            routed[branch].append((group, cid))
    errors += [f"{cid} not routed" for cid in sorted(set(rows) - seen)]
    for branch in BRANCHES:
        folder = BUILD / "distill" / "branches" / branch
        folder.mkdir(parents=True, exist_ok=True)
        out = [f"# Claims routed to {branch} (generated by claims_index.py split; do not edit)", "",
               "Full rows from the stage-3 claim tables, with the slot and the routing group.", "",
               "| slot | group | " + " | ".join(HEADER) + " |", "|" + "---|" * (len(HEADER) + 2)]
        for group, cid in sorted(routed[branch]):
            slot, line = rows[cid]
            out.append(f"| {slot} | {group} " + line.strip())
        (folder / "claims.md").write_text("\n".join(out) + "\n")
        print(f"{branch}: {len(routed[branch])} claims")
    for e in errors:
        print("ERROR", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(index() if sys.argv[1:] == ["index"] else split())
