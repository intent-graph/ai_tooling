ProjectMaker = Callable[[Path], Path]


def cli_run(project: Path, engine: str) -> int:
    assert main(["--project", str(project), "run", "--engine", engine, "--label", engine]) == 0
    return int(connect(project / "project.sqlite").execute("SELECT MAX(run_id) FROM run").fetchone()[0])


def api_run(project: Path, engine: str, chat: Chat | None = None, judge_note: str = "", minor_tolerance: int = 1,
            names: list[str] | None = None, generator: ModelRef | None = None) -> tuple[int, Exception | None]:
    """Create a run through the runner's API, optionally with another chat backend; return it and any pause."""
    cfg = config.load(project)
    adapters = _adapters(project, cfg)
    if generator is not None:
        adapters.generator.model = generator
    conn = connect(project / "project.sqlite")
    defects = load_defects()
    versions = RunVersions(
        engine, None, cfg.budget, minor_tolerance, load_release(defects), defects,
        InstructionStack("generator", "fake/generator", load_base("generator")),
        InstructionStack("judge", "fake/judge", load_base("judge") + judge_note), repo.latest_rule_set(conn),
    )
    run_id = create_run(conn, adapters, versions, names or [p.source_name for p in repo.photos(conn)])
    try:
        execute_run(replace(adapters, chat=chat) if chat else adapters, run_id)
    except RunPaused as paused:
        return run_id, paused
    return run_id, None


def points(project: Path, run_id: int) -> list[list[tuple[tuple[str, int], ...]]]:
    conn = connect(project / "project.sqlite")
    return [[e.point.levels for e in repo.history(conn, opt["optimization_id"], 0, 0)]
            for opt in repo.optimizations(conn, run_id)]


def test_three_engines_on_a_known_landscape(project: Path) -> None:
    single, coordinate, guided = cli_run(project, "single"), cli_run(project, "coordinate"), cli_run(project, "guided")
    conn = connect(project / "project.sqlite")
    report = build(conn, [single, coordinate, guided])
    by_engine = {r["engine"]: r for r in report["runs"]}
    assert by_engine["single"]["accepted_by_judge"] == 0
    assert by_engine["guided"]["accepted_by_judge"] == 3  # the judge's move (two references) removes the door
    assert by_engine["guided"]["attempts"] < by_engine["coordinate"]["attempts"]
    assert by_engine["guided"]["attempts_cached"] >= 3  # its start points were generated by the single run
    assert report["comparable"]
    first = conn.execute(
        "SELECT COUNT(DISTINCT request_sha256), COUNT(*), SUM(cached) FROM attempt WHERE seq = 1"
    ).fetchone()
    assert tuple(first) == (3, 9, 6)  # three photos x three engines: each start point requested thrice, made once


def test_runs_that_differ_in_budget_are_not_comparable(project: Path) -> None:
    single = cli_run(project, "single")
    text = (project / "project.toml").read_text(encoding="utf-8").replace("max_attempts = 6", "max_attempts = 3")
    (project / "project.toml").write_text(text, encoding="utf-8")
    guided = cli_run(project, "guided")
    assert comparability(connect(project / "project.sqlite"), [single, guided]) == ["runs differ in budget_json"]


def test_runs_may_differ_in_one_factor_engine_or_generator(project: Path) -> None:
    single, _ = api_run(project, "single")
    other_generator, _ = api_run(project, "single", generator=ModelRef("fake/generator-b", "1"))
    other_both, _ = api_run(project, "guided", generator=ModelRef("fake/generator-b", "1"))
    conn = connect(project / "project.sqlite")
    report = build(conn, [single, other_generator])
    assert report["comparable"] and [r["generator"] for r in report["runs"]] == ["fake/generator", "fake/generator-b"]
    assert report["runs"][1]["attempts_cached"] == 0  # another generator never reuses the first one's images
    assert comparability(conn, [single, other_both]) == ["runs differ in more than one factor: engine, generator"]


def test_a_paused_run_resumes_to_the_same_result(tmp_path: Path, make_project: ProjectMaker) -> None:
    straight = make_project(tmp_path / "straight")
    reference, pause = api_run(straight, "guided")
    assert pause is None

    project = make_project(tmp_path / "paused")
    backend = FakeChat()
    calls = {"n": 0}

    def flaky(messages: list[dict[str, object]], schema: dict[str, object]) -> str:
        calls["n"] += 1
        if calls["n"] == 2:
            raise EndpointError("endpoint_unreachable", "machine gone")
        return backend(messages, schema)

    run_id, pause = api_run(project, "guided", chat=flaky)
    assert isinstance(pause, RunPaused)
    conn = connect(project / "project.sqlite")
    assert len(repo.optimizations(conn, run_id, "running")) == 3
    cfg = config.load(project)
    execute_run(_adapters(project, cfg), run_id)  # resume: replay the stored history, judge what was not, go on
    assert not repo.optimizations(conn, run_id, "running")
    assert points(project, run_id) == points(straight, reference)


def test_a_broken_judge_answer_is_stored_and_retried(project: Path) -> None:
    run_id, _ = api_run(project, "single", chat=FakeChat(broken_first=True), names=["room_0.jpg"])
    rows = connect(project / "project.sqlite").execute(
        "SELECT parse_error IS NOT NULL FROM judgment j JOIN attempt a USING (attempt_id) "
        "JOIN optimization o USING (optimization_id) WHERE o.run_id = ? ORDER BY judgment_id", (run_id,)
    ).fetchall()
    assert [r[0] for r in rows] == [1, 0]


def test_deliver_and_export(project: Path, tmp_path: Path) -> None:
    guided = cli_run(project, "guided")
    assert main(["--project", str(project), "deliver", "--run", str(guided)]) == 0
    out = tmp_path / "out"
    assert main(["--project", str(project), "export", str(out)]) == 0
    manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    assert {m["outcome"] for m in manifest} == {"emptied"} and len(list(out.glob("*_empty.png"))) == 3


def test_keys_never_go_in_the_project_file(project: Path) -> None:
    text = (project / "project.toml").read_text(encoding="utf-8").replace('key_file = ""', 'key = "secret"', 1)
    (project / "project.toml").write_text(text, encoding="utf-8")
    with pytest.raises(config.ConfigError):
        config.load(project)


def test_an_empty_mask_sets_the_photo_aside(project: Path, tmp_path: Path) -> None:
    import numpy as np
    from PIL import Image

    empty = tmp_path / "empty_masks"
    empty.mkdir()
    Image.fromarray(np.zeros((240, 320), dtype=np.uint8)).save(empty / "room_1.png")
    assert main(["--project", str(project), "masks", str(empty)]) == 0
    conn = connect(project / "project.sqlite")
    photo = repo.photos(conn, ["room_1.jpg"])[0]
    found = repo.eligibility(conn, photo.photo_id, repo.latest_rule_set(conn))
    assert found is not None and (found.decision, found.reason) == ("skip", "nothing_to_remove")
    with pytest.raises(LookupError, match="set aside"):
        api_run(project, "single", names=["room_1.jpg"])
    run_id = cli_run(project, "single")  # without a list: the photo is left out
    assert len(repo.optimizations(conn, run_id)) == 2
